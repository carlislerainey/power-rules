#!/usr/bin/perl
# copy the pieces the HTML version needs out of the paper's LaTeX source, into <out dir>
#   - title.tex: the title (\titlemain and \titlesub, as defined in the main text)
#   - abstract.tex: the abstract (between "%%% begin abstract" and "%%% end abstract")
#   - body.tex: the body (between "%%% begin body" and "%%% end body")
#   - appendix.tex (from the appendix file): from \appendix up to its \printbibliography
# the pieces are copied byte for byte, so the text of the HTML is the paper's text; the one
# exception is the appendix's restatement of the rules (Appendix 4), where each rule box becomes
# the main text's \name* (so that the HTML repeats the main text's box), and only if the box is
# the main text's rule word for word
use strict;
use warnings;

my ($src, $app, $dir) = @ARGV;
die "usage: extract.pl <main text .tex> <appendix .tex> <out dir>\n" unless $dir;

sub slurp { my $f = shift; open(my $fh, '<', $f) or die "cannot read $f: $!\n"; local $/; return <$fh>; }
my $tex = slurp($src);
my $apx = slurp($app);

# each marker must appear exactly once
for my $marker ('\newcommand{\titlemain}{', '\newcommand{\titlesub}{', "\n%%% begin abstract\n",
                "\n%%% end abstract\n", "\n%%% begin body\n", "\n%%% end body\n") {
  my $n = () = $tex =~ /\Q$marker\E/g;
  die "expected one $marker in $src, found $n\n" unless $n == 1;
}
for my $marker ("\n\\appendix\n", '\printbibliography', '\setcounter{table}{2}') {
  my $n = () = $apx =~ /\Q$marker\E/g;
  die "expected one $marker in $app, found $n\n" unless $n == 1;
}
my ($main) = $tex =~ /\\newcommand\{\\titlemain\}\{([^{}]*)\}/ or die "cannot read \\titlemain in $src\n";
my ($sub)  = $tex =~ /\\newcommand\{\\titlesub\}\{([^{}]*)\}/  or die "cannot read \\titlesub in $src\n";
my ($abstract) = $tex =~ /\n%%% begin abstract\n(.*?\n)%%% end abstract\n/s;
my ($body)     = $tex =~ /\n%%% begin body\n(.*?\n)%%% end body\n/s;
my ($appendix) = $apx =~ /(?<=\n)(\\appendix\n.*?)\\printbibliography/s;

# the appendix file's own table numbering (Tables 1 and 2 are in the main text) is not needed
# after the main text
$appendix =~ s/% Tables 1 and 2 are in the main text\n\\setcounter\{table\}\{2\}\n//
  or die "cannot find the table counter in $app\n";

# the rules: each restated box in the appendix must be the main text's rule
my %rules;  # label -> [title, name, body]
while ($body =~ /\\begin\{restatable\}\[(.*?)\]\{rule0\}\{(\w+)\}\n\\label\{([^}]+)\}\n(.*?)\\end\{restatable\}/sg) {
  $rules{$3} = [$1, $2, $4];
}
die "expected 7 rules in $src, found " . keys(%rules) . "\n" unless keys %rules == 7;
sub restate {
  my ($title, $label, $text) = @_;
  my $rule = $rules{$label} or die "the appendix restates $label, which is not a rule in $src\n";
  die "the appendix's $label is not the main text's rule word for word\n"
    unless $title eq $rule->[0] && $text eq $rule->[2];
  return "\\$rule->[1]*";
}
my $n = ($appendix =~ s/\\begin\{rule0\}\[(.*?)\]\n\\label\{([^}]+)\}\n(.*?)\\end\{rule0\}/restate($1, $2, $3)/gse);
die "expected 7 restated rules in $app, found $n\n" unless $n == 7;
die "a rule box in $app is not in the expected form\n" if $appendix =~ /\\begin\{rule0\}/;

use File::Path qw(make_path);
make_path($dir) unless -d $dir;
my %pieces = (
  'title.tex'    => ["\\newcommand{\\titlemain}{$main}\n\\newcommand{\\titlesub}{$sub}\n", $src],
  'abstract.tex' => [$abstract, $src],
  'body.tex'     => [$body, $src],
  'appendix.tex' => [$appendix, $app],
);
for my $file (sort keys %pieces) {
  my ($text, $from) = @{$pieces{$file}};
  open(my $out, '>', "$dir/$file") or die "cannot write $dir/$file: $!\n";
  print $out "% generated by extract.pl from $from; do not edit\n", $text;
  close $out;
}
